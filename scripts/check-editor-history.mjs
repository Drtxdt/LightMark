import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { Text, EditorSelection } from '@codemirror/state';
import { compileTypeScriptModuleGraph } from './transpile-module-graph.mjs';
const temp = fs.mkdtempSync(path.resolve('node_modules/.lightmark-document-history-'));
try {
  const { DocumentHistory } = await import(pathToFileURL(compileTypeScriptModuleGraph(path.resolve('src/editor/documentHistory.ts'), temp)).href);
  const root = text => ({ mode: 'source', doc: Text.of([text]), lineEndings: {} });
  const caret = n => ({ anchor: n, head: n });
  const history = new DocumentHistory();
  const original = root('');
  history.mount(original, caret(0), '');
  const edit = (text, before, time, kind = 'typing') => history.record(root(text), { kind, before: caret(before), after: caret(text.length), time });
  edit('a', 0, 100);
  edit('ab', 1, 500);
  assert.equal(history.prepare(-1).version.primary.root, original);
  edit('abc', 2, 1001);
  assert.equal(history.prepare(-1).version.primary.root.doc.toString(), 'ab');
  history.checkpoint('abc'); history.markSaved('abc');
  const saved = history.current;
  const visualRoot = { mode: 'wysiwyg', doc: { immutable: true }, baseline: {} };
  history.mount(visualRoot, caret(3), 'abc');
  assert.equal(history.current, saved, 'remount must not replace history');
  assert.equal(history.projection(saved, 'wysiwyg').root.mode, 'source', 'mount must retain the old bookmark until precise restoration');
  history.project(visualRoot, caret(3));
  assert.equal(history.projection(saved, 'wysiwyg').root, visualRoot);
  const move = history.prepare(-1);
  assert.throws(() => history.commit(move, () => { throw new Error('conversion failed'); }), /conversion failed/);
  assert.equal(history.current, saved);
  assert.equal(history.prepare(-1).version, move.version, 'failed publication leaves cursor unchanged');
  history.commit(move, () => {});
  assert.equal(history.isSaved(history.current), false);
  history.commit(history.prepare(1), () => {});
  assert.equal(history.isSaved(history.current), true);
  history.commit(history.prepare(-1), () => {});
  edit('ab!', 2, 1200, 'command');
  assert.equal(history.canRedo, false);
  const stale = history.prepare(-1);
  edit('ab!?', 3, 1300, 'command');
  assert.throws(() => history.commit(stale, () => assert.fail('must not publish')), /过期/);
  const bookmarks = new DocumentHistory();
  bookmarks.mount(root('A'), caret(0), 'A');
  const beforeBookmarkEdit = bookmarks.current;
  const visualBefore = { mode: 'wysiwyg', doc: { immutable: 'before' }, baseline: {} };
  bookmarks.project(visualBefore, caret(31));
  bookmarks.record({ ...visualBefore, doc: { immutable: 'after' } }, { kind: 'command', before: caret(31), after: caret(32), time: 1 });
  assert.equal(bookmarks.projection(beforeBookmarkEdit, 'source').root, visualBefore, 'cross-mode replay must convert the newest selection projection, not a stale cached source bookmark');
  assert.deepEqual(bookmarks.projection(beforeBookmarkEdit, 'source').bookmark, caret(31));
  const getters = new DocumentHistory();
  getters.mount(root('abc'), EditorSelection.range(1, 2), 'abc');
  assert.deepEqual(getters.current.primary.bookmark, { anchor: 1, head: 2 }, 'CodeMirror range getters must be copied explicitly');
  getters.project(root('abc'), EditorSelection.range(2, 3));
  assert.deepEqual(getters.projection(getters.current, 'wysiwyg').bookmark, { anchor: 2, head: 3 });
  getters.record(root('abcd'), { kind: 'command', before: EditorSelection.range(2, 3), after: EditorSelection.cursor(4), time: 1 });
  assert.deepEqual(getters.current.primary.bookmark, { anchor: 4, head: 4 });
  const source = fs.readFileSync('src/components/editor/SourceEditor.vue', 'utf8');
  const wys = fs.readFileSync('src/components/editor/WysiwygEditor.vue', 'utf8');
  assert.ok(source.includes('moveDocumentHistory') && source.includes('captureHistoryRoot'));
  assert.ok(wys.includes('moveDocumentHistory') && wys.includes('undoRedo: false') && wys.includes('prepareHistoryReplay'));
  assert.ok(!wys.includes('wysiwygFormatHistory.undo.push'));
  console.log('Document history: grouping, remount, rollback, save, branching and stale replay passed.');
} finally { fs.rmSync(temp, { recursive: true, force: true }); }
