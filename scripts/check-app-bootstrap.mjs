import assert from 'node:assert/strict';
import fs from 'node:fs';
import ts from 'typescript';
const source=fs.readFileSync('src/stores/appStore.ts','utf8');
const ast=ts.createSourceFile('appStore.ts',source,ts.ScriptTarget.Latest,true);
const declaration=ast.statements.find(s=>ts.isFunctionDeclaration(s)&&s.name?.text==='loadConfig');
assert.ok(declaration);
const js=ts.transpileModule(declaration.getText(ast).replace(/^export\s+/,''),{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.ESNext}}).outputText;
const create=new Function('readConfigState','ensureDefaultTab',`let configLoadPromise=null; ${js};return loadConfig;`);
let calls=0,release,defaults=0;
const load=create(()=>{calls++;return new Promise(resolve=>release=resolve)},()=>defaults++);
const a=load(),b=load();assert.equal(a,b);assert.equal(calls,1);
release();await a;
assert.equal(defaults,1,'the activation target exists before early file commands continue');
assert.equal(load(),a,'later App mount must not reset the document generation');
assert.equal(calls,1);
const failure=Error('config read unavailable');let failures=0;
const failed=create(()=>{failures++;return Promise.reject(failure)},()=>{});
await assert.rejects(failed(),error=>error===failure);
await assert.rejects(failed(),error=>error===failure);
assert.equal(failures,1,'a failed bootstrap cannot later reset opened documents');
console.log('Application bootstrap is shared and starts only one document generation.');
